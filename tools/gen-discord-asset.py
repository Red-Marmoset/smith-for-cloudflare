#!/usr/bin/env python3
# gen-discord-asset.py - embed tools/smith-discord-bot.py + requirements into
# Modules/SmithAgent/DiscordBotAsset.h so the agent can materialize + run the bot
# with no sibling files. Re-run after editing the bot.
#
#   python3 tools/gen-discord-asset.py
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOT = os.path.join(ROOT, "tools", "smith-discord-bot.py")
REQ = os.path.join(ROOT, "tools", "smith-discord-requirements.txt")
OUT = os.path.join(ROOT, "Modules", "SmithAgent", "DiscordBotAsset.h")

def raw(text, delim):
    if (")" + delim + '"') in text:
        sys.exit("delimiter %r collides with content" % delim)
    return 'R"' + delim + "(" + text + ")" + delim + '"'

# MSVC rejects single string literals over 16380 bytes (C2026), so emit the text
# as adjacent raw literals of at most `limit` bytes (split on line boundaries);
# the compiler concatenates them (total cap 64KB - plenty for the bot script).
def raw_chunked(text, delim, limit=15000):
    chunks, cur = [], ""
    for line in text.splitlines(keepends=True):
        if cur and len(cur) + len(line) > limit:
            chunks.append(cur)
            cur = ""
        cur += line
    if cur:
        chunks.append(cur)
    return "\n        ".join(raw(c, delim) for c in chunks)

with open(BOT, "r", encoding="utf-8") as f: bot = f.read()
with open(REQ, "r", encoding="utf-8") as f: req = f.read()

# MSVC's concatenated-literal cap is 64KB; fail loudly at ~60KB so the limit is
# hit here (with a clear message) and never as an obscure compiler error.
LIMIT = 60 * 1024
if len(bot) + len(req) > LIMIT:
    sys.exit("embedded bot has grown to %d bytes (limit %d): split it or trim it "
             "before it hits MSVC's 64KB string cap" % (len(bot) + len(req), LIMIT))

h = """// DiscordBotAsset.h - the Discord bot script, embedded so the agent is self-contained.
// GENERATED by tools/gen-discord-asset.py from tools/smith-discord-bot.py. Do not edit by hand.
//
// The agent materializes these to <workspace>/.smith-discord/ and runs the bot in a Python
// venv. The canonical source is tools/smith-discord-bot.py (also runnable standalone + unit
// tested by tools/test_discord_bot.py).
//
// Copyright (c) 2026 Red Marmoset Studios Ltd.
#pragma once

namespace Smith
{
    inline const char* kDiscordRequirements = %s;

    inline const char* kDiscordBotPy = %s;
}
""" % (raw(req, "REQEOF"), raw_chunked(bot, "PYEOF"))

with open(OUT, "w", encoding="utf-8") as f:
    f.write(h)
print("Embedded smith-discord-bot.py (%d bytes) + requirements (%d bytes) -> %s" % (len(bot), len(req), OUT))
