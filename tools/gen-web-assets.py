#!/usr/bin/env python3
# gen-web-assets.py - portable twin of gen-web-assets.ps1: embed every file under web/
# into Modules/SmithCoordinator/WebAssets.cpp so the coordinator serves the UI as a
# single self-contained binary. Re-run after editing web/.
#
#   python3 tools/gen-web-assets.py
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, "web")
OUT = os.path.join(ROOT, "Modules", "SmithCoordinator", "WebAssets.cpp")

def content_type(name):
    n = name.lower()
    if n.endswith((".html", ".htm")): return "text/html; charset=utf-8"
    if n.endswith(".css"): return "text/css; charset=utf-8"
    if n.endswith((".js", ".mjs")): return "text/javascript; charset=utf-8"
    if n.endswith(".json"): return "application/json"
    if n.endswith(".png"): return "image/png"
    if n.endswith(".svg"): return "image/svg+xml"
    if n.endswith(".ico"): return "image/x-icon"
    return "application/octet-stream"

files = []
for dirpath, _, names in os.walk(WEB):
    for nm in names:
        files.append(os.path.join(dirpath, nm))
files.sort()

out = []
out.append("// WebAssets.cpp - GENERATED by tools/gen-web-assets.ps1. Do not edit by hand.")
out.append("// Embeds web/ so the coordinator serves the UI as a single self-contained binary.")
out.append('#include "WebAssets.h"')
out.append("namespace Smith {")

entries = []
for idx, path in enumerate(files):
    with open(path, "rb") as fh:
        data = fh.read()
    rel = os.path.relpath(path, WEB).replace("\\", "/")
    var = "kAsset%d" % idx
    out.append("static const unsigned char %s[] = {" % var)
    line = "  "
    for i, b in enumerate(data):
        line += "0x%02x," % b
        if (i + 1) % 20 == 0:
            out.append(line); line = "  "
    if line.strip():
        out.append(line)
    out.append("};")
    entries.append((rel, var, len(data), content_type(os.path.basename(path))))

out.append("static const WebAsset kAssets[] = {")
for rel, var, ln, ct in entries:
    out.append('  { "%s", %s, %du, "%s" },' % (rel, var, ln, ct))
out.append("  { nullptr, nullptr, 0u, nullptr }")
out.append("};")
out.append("const WebAsset* WebAssets() { return kAssets; }")
out.append("int WebAssetCount() { return %d; }" % len(entries))
out.append("}")

with open(OUT, "w", encoding="ascii") as fh:
    fh.write("\n".join(out) + "\n")

total = sum(e[2] for e in entries)
print("Embedded %d asset(s), %d bytes -> %s" % (len(entries), total, OUT))
for rel, _, ln, ct in entries:
    print("  %-18s %8d bytes  %s" % (rel, ln, ct))
