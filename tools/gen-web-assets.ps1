# gen-web-assets.ps1 - embed every file under web/ into
# Modules/SmithCoordinator/WebAssets.cpp so the coordinator can serve the UI with
# no sibling files (single self-contained binary). Re-run after editing web/.
#
#   .\tools\gen-web-assets.ps1
param(
    [string]$WebDir,
    [string]$OutFile
)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
if (-not $WebDir)  { $WebDir  = Join-Path $root "web" }
if (-not $OutFile) { $OutFile = Join-Path $root "Modules\SmithCoordinator\WebAssets.cpp" }

function Get-ContentType($name) {
    switch -Regex ($name) {
        '\.html?$' { 'text/html; charset=utf-8'; break }
        '\.css$'   { 'text/css; charset=utf-8'; break }
        '\.m?js$'  { 'text/javascript; charset=utf-8'; break }
        '\.json$'  { 'application/json'; break }
        '\.png$'   { 'image/png'; break }
        '\.svg$'   { 'image/svg+xml'; break }
        '\.ico$'   { 'image/x-icon'; break }
        default    { 'application/octet-stream' }
    }
}

$files = Get-ChildItem -Path $WebDir -File -Recurse | Sort-Object FullName
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// WebAssets.cpp - GENERATED by tools/gen-web-assets.ps1. Do not edit by hand.")
[void]$sb.AppendLine("// Embeds web/ so the coordinator serves the UI as a single self-contained binary.")
[void]$sb.AppendLine('#include "WebAssets.h"')
[void]$sb.AppendLine("namespace Smith {")

$entries = @()
$idx = 0
foreach ($f in $files) {
    $bytes = [System.IO.File]::ReadAllBytes($f.FullName)
    $rel = $f.FullName.Substring($WebDir.Length).TrimStart('\', '/').Replace('\', '/')
    $var = "kAsset$idx"
    [void]$sb.AppendLine("static const unsigned char $var[] = {")
    $line = "  "
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        $line += ("0x{0:x2}," -f $bytes[$i])
        if (($i + 1) % 20 -eq 0) { [void]$sb.AppendLine($line); $line = "  " }
    }
    if ($line.Trim().Length -gt 0) { [void]$sb.AppendLine($line) }
    [void]$sb.AppendLine("};")
    $entries += [pscustomobject]@{ rel = $rel; var = $var; len = $bytes.Length; ct = (Get-ContentType $f.Name) }
    $idx++
}

[void]$sb.AppendLine("static const WebAsset kAssets[] = {")
foreach ($e in $entries) {
    [void]$sb.AppendLine(('  {{ "{0}", {1}, {2}u, "{3}" }},' -f $e.rel, $e.var, $e.len, $e.ct))
}
[void]$sb.AppendLine("  { nullptr, nullptr, 0u, nullptr }")
[void]$sb.AppendLine("};")
[void]$sb.AppendLine("const WebAsset* WebAssets() { return kAssets; }")
[void]$sb.AppendLine(('int WebAssetCount() {{ return {0}; }}' -f $entries.Count))
[void]$sb.AppendLine("}")

Set-Content -Path $OutFile -Value $sb.ToString() -Encoding ascii
$total = ($entries | Measure-Object -Property len -Sum).Sum
Write-Host ("Embedded {0} asset(s), {1} bytes -> {2}" -f $entries.Count, $total, $OutFile)
foreach ($e in $entries) { Write-Host ("  {0,-18} {1,8} bytes  {2}" -f $e.rel, $e.len, $e.ct) }
